/**
 * Тексты про баллы (GIMN-030).
 *
 * Отдельным модулем без "server-only": сообщение в Telegram собирает
 * сервер, а склонение слова «балл» нужно ещё и разделу «Мои баллы» в
 * браузере. Держать одну и ту же таблицу окончаний в двух местах — верный
 * способ получить «5 балла» в одном из них.
 */

/** «1 балл», «2 балла», «5 баллов» — иначе счётчик выглядит машинным. */
export function pointsWord(n: number): string {
  const mod100 = Math.abs(n) % 100;
  const mod10 = mod100 % 10;
  if (mod100 >= 11 && mod100 <= 14) return "баллов";
  if (mod10 === 1) return "балл";
  if (mod10 >= 2 && mod10 <= 4) return "балла";
  return "баллов";
}

export type AwardMessage = {
  /** Имя из профиля. Пусто — обращаемся без имени, а не к «Пользователю». */
  name?: string | null;
  amount: number;
  /** За что начислено — уходит человеку как есть, поэтому без служебных слов. */
  reason: string;
  /** Остаток ПОСЛЕ начисления. */
  balance: number;
};

/**
 * Сообщение о начислении. Текст — дословно из батча GIMN-030.
 *
 * Последняя фраза обязательна: баллы начисляются, когда платного режима
 * ещё нет, и без неё сообщение выглядит обещанием скидки, которой прямо
 * сейчас негде взяться.
 */
export function pointsAwardedMessage({ name, amount, reason, balance }: AwardMessage): string {
  const who = name?.trim() ? `${name.trim()}, вам` : "Вам";
  return [
    `🎁 ${who} начислено +${amount} ${pointsWord(amount)}!`,
    "",
    `За что: ${reason}`,
    `Ваш баланс: ${balance} ${pointsWord(balance)}`,
    "",
    "Баллы применятся при выборе тарифа",
    "после запуска платного режима.",
  ].join("\n");
}
