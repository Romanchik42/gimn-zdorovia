export const LAST_STEP = TOUR_STEPS.length - 1;

/** Шаги, на которых кнопка «Начать» приглушена: до финального включительно. */
export function startButtonMuted(index: number): boolean {
  return index >= 0 && index < LAST_STEP;
}

export function stepAt(index: number): TourStep | null {
  return TOUR_STEPS[index] ?? null;
}

/** Первый шаг тура, который живёт на этом экране. */
export function firstStepOnPath(path: string): number {
  return TOUR_STEPS.findIndex((s) => s.path === path);
}
