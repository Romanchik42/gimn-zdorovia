/**
 * Ознакомительный тур (GIMN-029).
 *
 * Шесть шагов, и каждый открывает тот экран, о котором рассказывает:
 * читать про питание, глядя на главную, — всё равно что изучать город по
 * описанию. Поэтому шаг знает свой адрес, и тур переходит по нему сам.
 *
 * Тексты — дословно из батча GIMN-029. Переносы строк в описании значимы:
 * подсказка выводит их как есть (white-space: pre-line), поэтому списки
 * остаются списками.
 *
 * Четыре подсказки из батча (баллы, режимы, диагностика, анкета) в тур не
 * входят: человек доходит до этих экранов в разное время, иногда через
 * недели. Они живут отдельно — в hints.ts.
 */

export type TourStep = {
  id: string;
  /** Экран, на котором показывается шаг. Тур переходит туда сам. */
  path: string;
  /** Что подсветить. Нет селектора — обзорный шаг без подсветки. */
  element?: string;
  title: string;
  description: string;
  /** Раскрыть этот <details> перед показом: иначе подсвечивать нечего. */
  expand?: string;
};

/** Подстановка имени: приветствие без имени звучит как объявление на вокзале. */
export function greeting(name: string | null | undefined): string {
  return name?.trim() ? `Здравствуйте, ${name.trim()}! 👋` : "Здравствуйте! 👋";
}

