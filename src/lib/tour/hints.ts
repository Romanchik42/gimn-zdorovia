export function isHintId(value: string): value is HintId {
  return (HINT_IDS as readonly string[]).includes(value);
}

/** Отметки приходят из JSONB — чужие значения отбрасываем. */
export function parseHintsSeen(value: unknown): HintId[] {
  if (!Array.isArray(value)) return [];
  return value.filter((v): v is HintId => typeof v === "string" && isHintId(v));
}
