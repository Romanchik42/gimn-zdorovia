/**
 * Документ для ревматолога по упражнениям зала (GIMN-028, блок D).
 *
 * Отдельный от общего DOC_REVMATOLOG_FULL: там сто с лишним домашних
 * упражнений, и девятнадцать новых силовых утонули бы в них, а решение
 * нужно именно по ним. Общий документ остаётся как был.
 *
 * Разбор — тот же, что у общего документа (scripts/lib/seed-exercises.mjs),
 * чтобы описание в документе не разошлось с тем, что получает человек.
 *
 * Запуск: node scripts/build-doctor-gym-doc.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import {
  parseExercises,
  JOINT,
  LEVEL,
  POSITION,
  EQUIPMENT,
  contraList,
  effectList,
} from "./lib/seed-exercises.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const MIGRATION = "supabase/migrations/0026_gym_exercises_mvp.sql";
const OUT = path.join(ROOT, "DOC_REVMATOLOG_GYM_MVP.md");

/** Дозировка по уровням берётся из той же миграции — вторым её источником. */
function dosageRules(sql) {
  const rows = [...sql.matchAll(/\('(beginner|intermediate|advanced)',\s*(\d+),\s*(\d+),\s*(\d+),\s*(NULL::REAL|[\d.]+)\)/g)];
  return rows.map(([, level, sets, reps, rest, pct]) => ({
    level,
    sets: Number(sets),
    reps: Number(reps),
    rest: Number(rest),
    pct: pct.startsWith("NULL") ? null : Number(pct),
  }));
}

function kit(e) {
  const items = [e.equipment, ...(e.equipment_extra ?? [])]
    .filter((x) => x && x !== "none")
    .map((x) => EQUIPMENT[x] ?? x);
  return items.length ? items.join(" + ") : "без снаряда";
}

function render(e, index) {
  const lines = [];
  lines.push(`#### ${index}. ${e.name}`);
  lines.push("");
  lines.push(
    `**Уровень:** ${LEVEL[e.level] ?? e.level} · **Зона:** ${JOINT[e.target_joint] ?? e.target_joint} · **Снаряд:** ${kit(e)} · **Исходное положение:** ${POSITION[e.position ?? "any"] ?? e.position}`,
  );
  lines.push("");
  lines.push(`*${e.description}*`);
  lines.push("");
  lines.push("**Техника.**");
  lines.push("");
  for (const step of String(e.technique).split("\n")) {
    if (step.trim()) lines.push(step.trim());
  }
  lines.push("");

  const contra = contraList(e);
  lines.push(
    contra.length
      ? `**Противопоказания:** ${contra.join("; ")}.`
      : "**Противопоказания:** в справочнике не отмечены.",
  );
  lines.push("");

  const effects = effectList(e);
  if (effects.length) {
    lines.push(`**Реакция приложения на жалобу:** ${effects.join("; ")}.`);
    lines.push("");
  }

  lines.push("**Ваше решение:** одобрено / изменить технику / поднять уровень / исключить");
  lines.push("");
  return lines.join("\n");
}

const sql = readFileSync(path.join(ROOT, ...MIGRATION.split("/")), "utf8");
const gym = parseExercises(ROOT, [MIGRATION]).filter((e) => e.slug.startsWith("gym-"));
const rules = dosageRules(sql);

const byLevel = (level) => gym.filter((e) => e.level === level);
const today = new Date().toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric" });

const levelTable = rules
  .map((r) => `| ${LEVEL[r.level]} | ${r.sets}×${r.reps} | ${r.rest} сек | ${r.pct ? `~${Math.round(r.pct * 100)}% от максимума` : "пустой гриф или лёгкая гантель"} |`)
  .join("\n");

const listOf = (level) =>
  byLevel(level).length
    ? byLevel(level).map((e) => `${e.name} (${kit(e)})`).join(", ")
    : "—";

let doc = `# Упражнения в зале — на согласование

Материал для врача-ревматолога. Собран ${today} скриптом
\`scripts/build-doctor-gym-doc.mjs\` из миграции \`${MIGRATION}\` — то есть
описывает ровно то, что получит пользователь, без пересказа.

**Статус: не выкачено.** Код лежит в ветке \`feature/gym-exercises-mvp\` и
в приложение не попадёт, пока не будет вашего решения. Домашняя программа,
которую вы уже смотрели, работает и этими упражнениями не затронута.

**Что это.** Девятнадцать силовых упражнений для тех, кто занимается в
тренажёрном зале. Доступны только в программе «общая форма». В программе
реабилитации при болезни Бехтерева они не появляются ни при каком ответе
анкеты: запрет стоит на уровне кода и проверяется автоматически при каждой
сборке — упражнение со снарядом в эту программу не проходит.

**Как приложение решает, что дать человеку.** Учитываются: снаряжение,
которое человек отметил (нет скамьи — жим лёжа не предлагается), уровень
подготовки и противопоказания по зонам боли, отмеченные в анкете и во время
занятий. Те же ограничения, что и в домашней программе.

**Дозировка по уровням.**

| Уровень | Подходы | Отдых между подходами | Вес |
|---|---|---|---|
${levelTable}

---

## Главное, на что нужен ваш ответ

1. **Кому это вообще можно.** Сейчас силовой день получает любой человек в
   программе «общая форма», указавший, что занимается в зале, — в том числе
   тот, у кого есть диагноз, но кто выбрал вторую программу. Нужно ли
   закрыть зал для людей с установленным анкилозирующим спондилитом
   полностью, или допустимо при неактивном течении и с ограничениями?

2. **Осевая нагрузка.** Приседания со штангой, становая тяга и жим стоя
   дают осевую нагрузку на позвоночник. Сейчас они закрыты новичку и
   открываются только на среднем и продвинутом уровнях (двадцать
   тренировок, рост рабочего веса, двенадцать недель без пропусков). Этого
   достаточно, или их следует убрать совсем?

3. **Уровни.** Ниже упражнения разнесены по уровням. Начальный: ${listOf("beginner")}.
   Средний: ${listOf("intermediate")}. Продвинутый: ${listOf("advanced")}.
   Что переставить?

4. **Противопоказания.** У каждого упражнения отмечены зоны, при боли в
   которых оно не предлагается. Чего не хватает — особенно по давлению и
   по коленям?

5. **Дозировка.** Разумны ли 3×8 для начинающего и отдых 90 секунд?
   Стартовые веса — пустой гриф 20 кг, гантель 6–8 кг — не велики ли?

6. **Разминка.** Перед силовой частью приложение само ставит два
   разминочных упражнения и растяжку в конце. Достаточно ли этого перед
   работой со штангой?

---

`;

for (const [title, level, note] of [
  ["Начальный уровень", "beginner", "Эти упражнения получает человек, только начавший заниматься. Свободной штанги здесь нет намеренно."],
  ["Средний уровень", "intermediate", "Открываются, когда за плечами двадцать тренировок, рост рабочего веса не меньше 30% и двенадцать недель без пропусков дольше недели."],
  ["Продвинутый уровень", "advanced", "Самое требовательное к технике."],
]) {
  const list = byLevel(level);
  if (!list.length) continue;
  doc += `## ${title} (${list.length})\n\n${note}\n\n`;
  list.forEach((e, i) => {
    doc += `${render(e, i + 1)}\n`;
  });
  doc += "---\n\n";
}

doc += `## Что приложение делает само

- Не предлагает упражнение, если у человека нет нужного снаряда.
- Не предлагает упражнение, если человек отметил боль в соответствующей зоне.
- После жалобы во время занятия снижает нагрузку на неделю или исключает упражнение.
- Повышает уровень только с согласия человека, и только вверх.
- Вес добавляет по факту выполненного: три удачных занятия подряд — плюс
  2,5 кг на верх тела или 5 кг на низ; два неудачных — минус 10%.

## Чего приложение не делает

Не ставит диагноз, не назначает лечение, не отменяет назначения врача и не
заменяет осмотр. Материал собран по общедоступным рекомендациям и является
вспомогательным.
`;

writeFileSync(OUT, doc, "utf8");
console.log(`${path.basename(OUT)}: ${gym.length} упражнений, ${(doc.length / 1024).toFixed(1)} КиБ`);
