-- 0019 (GIMN-021): описания без названия диагноза.
--
-- Было: у четырёх упражнений в поле description стояло «при Бехтерева».
-- Стало: тот же смысл через анатомию — что именно скованно и почему это
-- упражнение помогает. Название болезни в карточке упражнения не нужно:
-- человек выбирает программу один раз при входе, а в каталоге видит
-- движение, а не диагноз.
--
-- Тексты ТЕХНИКИ (exercises.technique) не менялись и не будут: их
-- согласует врач. Здесь правится только однострочное пояснение, зачем
-- упражнение нужно. Прежние формулировки сохранены в комментариях ниже,
-- чтобы врач при разборе видел, что именно поменялось.

-- было: «Поддерживает подвижность рёберно-позвоночных суставов — при Бехтерева это ключевое.»
UPDATE exercises SET description =
  'Поддерживает подвижность рёберно-позвоночных суставов — от неё зависит глубина дыхания.'
WHERE slug = 'breath-chest-expand';

-- было: «Возвращает вращение грудному отделу — первое, что теряется при Бехтерева.»
UPDATE exercises SET description =
  'Возвращает вращение грудному отделу — оно теряется первым при скованности спины.'
WHERE slug = 'main-thoracic-rotation';

-- было: «Расслабляет ягодичные мышцы, которые при Бехтерева часто перенапряжены.»
UPDATE exercises SET description =
  'Расслабляет ягодичные мышцы — при скованности таза они часто перенапряжены.'
WHERE slug = 'massage-glutes-ball';

-- было: «Снимает напряжение в глубине ягодицы, частое при Бехтерева.»
UPDATE exercises SET description =
  'Снимает напряжение в глубине ягодицы — частую причину боли, отдающей в бедро.'
WHERE slug = 'stretch-piriformis';
