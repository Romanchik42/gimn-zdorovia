-- 0028 (GIMN-029): отметки о показанных подсказках.
--
-- Тур из шести шагов проходят один раз, и для него уже есть
-- users.tour_completed. Но четыре подсказки показываются не в туре, а при
-- первом открытии своего экрана: баллы, переключатель режимов,
-- углублённая диагностика, анкета общего режима. Человек доходит до них в
-- разное время, иногда через недели после тура.
--
-- Отсюда одна колонка со списком, а не четыре булевых: подсказки будут
-- появляться и дальше, и каждая новая иначе означала бы новую колонку,
-- новую миграцию и новую строку в GRANT — при том что содержательно это
-- одна и та же отметка «видел».

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS hints_seen JSONB NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN users.hints_seen IS
  'Показанные контекстные подсказки: ["points","modes"] (0028)';

-- Поколоночные права (0011): без этой строки подсказка «сохранилась бы»,
-- но не сохранилась — запись молча не проходит, и человек видел бы одно и
-- то же при каждом открытии экрана.
GRANT UPDATE (hints_seen) ON public.users TO authenticated;

NOTIFY pgrst, 'reload schema';
