-- 0022 (GIMN-028): «Свой вариант» в опросе «Что случилось?».
--
-- Список симптомов закрыт семью кнопками, а сказать человек может что
-- угодно: «немеет рука», «щёлкает колено», «не понял технику». До сих пор
-- такому просто не было места, и опрос молча терял то, ради чего его
-- открывали.
--
-- Отдельная колонка для свободного текста НЕ заводится: она уже есть —
-- side_effect_events.description, и значение 'other' уже разрешено
-- ограничением этой таблицы. Экран тренировки тоже давно умеет печатать
-- описание вместо названия симптома, когда симптом 'other'. Не хватало
-- ровно одного — правила в Decision Tree: без него API отвечает
-- «для этого симптома не настроено правило» и отметка пропадает.
--
-- Совет намеренно общий: что именно случилось, знает только человек, и
-- сочинять за него медицинскую рекомендацию нельзя. Поэтому предлагаем
-- остановиться, оценить состояние и говорим, что сообщение прочитают.
--
-- next_workout_adjustment = 'lighter_only': причина неизвестна, значит
-- следующее занятие делаем осторожнее. Порог визита к врачу — 3, как у
-- остальных настоящих симптомов: 'other' не считается пустяком.

INSERT INTO side_effect_rules
  (symptom, conditions, advice, next_workout_adjustment, skip_exercise, require_doctor_visit_threshold, priority)
SELECT
  'other',
  '{}'::jsonb,
  '[{"order":1,"text":"Остановите упражнение и отдохните минуту."},
    {"order":2,"text":"Оцените самочувствие: если что-то болит или кружится голова — заканчивайте занятие."},
    {"order":3,"text":"Мы прочитаем ваше сообщение и учтём его в следующей тренировке."},
    {"order":4,"text":"Если состояние не улучшается — обратитесь к врачу."}]'::jsonb,
  'lighter_only',
  FALSE,
  3,
  10
WHERE NOT EXISTS (
  SELECT 1 FROM side_effect_rules WHERE symptom = 'other' AND conditions = '{}'::jsonb
);

