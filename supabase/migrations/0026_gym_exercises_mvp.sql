-- ---------------------------------------------------------------------------
-- 3. Дозировка.
--
-- Правило одно на всех, поэтому оно и записано один раз, а не размножено
-- в пятьдесят семь строк: новичку 3×8 с отдыхом 90 секунд и понятным
-- стартовым весом, среднему 4×8 через 120 секунд и около 60% от
-- одноповторного максимума, продвинутому 5×5 через 180 секунд и около 75%.
--
-- Стартовый вес проставлен только новичку. Дальше вес считается от того,
-- что человек реально поднял (блок F), и справочник в это уже не лезет.
-- ---------------------------------------------------------------------------

INSERT INTO exercise_dosage
  (exercise_id, level, mode, sets, reps_per_set, rest_between_sets_sec,
   weight_kg_default, weight_pct_1rm, notes)
SELECT e.id, p.level, 'general', p.sets, p.reps, p.rest,
       CASE WHEN p.level = 'beginner' THEN b.start_kg END,
       p.pct,
       CASE WHEN p.level = 'beginner'
            THEN 'Вес такой, чтобы последний повтор давался с запасом в силах'
       END
  FROM (VALUES
          ('gym-goblet-squat', 8::REAL),
          ('gym-leg-press', 40),
          ('gym-barbell-squat', 20),
          ('gym-leg-extension', 15),
          ('gym-leg-curl', 15),
          ('gym-calf-raise', 30),
          ('gym-kettlebell-swing', 12),
          ('gym-romanian-deadlift', 20),
          -- Штанга с блинами меньше 20 кг лежит слишком низко: тянуть с
          -- такой высоты новичку неудобно и небезопасно. Отсюда и 40.
          ('gym-barbell-deadlift', 40),
          ('gym-dumbbell-bench', 8),
          ('gym-bench-press', 20),
          ('gym-dumbbell-shoulder-press', 6),
          ('gym-overhead-press', 20),
          ('gym-dumbbell-row', 8),
          ('gym-lat-pulldown', 25),
          ('gym-cable-row', 25),
          ('gym-barbell-row', 20),
          ('gym-face-pull', 10)
       ) AS b(slug, start_kg)
  CROSS JOIN (VALUES
          ('beginner', 3, 8, 90, NULL::REAL),
          ('intermediate', 4, 8, 120, 0.60),
          ('advanced', 5, 5, 180, 0.75)
       ) AS p(level, sets, reps, rest, pct)
  JOIN exercises e ON e.slug = b.slug
ON CONFLICT (exercise_id, level, mode) DO NOTHING;

-- Прогулка фермера считается временем, а не повторами: «восемь повторов
-- ходьбы» — бессмыслица. Поэтому у неё подходы есть, а reps_per_set нет.
INSERT INTO exercise_dosage
  (exercise_id, level, mode, sets, duration_sec, rest_between_sets_sec, weight_kg_default, notes)
SELECT e.id, p.level, 'general', p.sets, p.hold, p.rest,
       CASE WHEN p.level = 'beginner' THEN 12::REAL END,
       'Идите ровно, пока держится осанка, — не пока держится хват'
  FROM (VALUES
          ('beginner', 3, 30, 90),
          ('intermediate', 4, 40, 90),
          ('advanced', 5, 45, 120)
       ) AS p(level, sets, hold, rest)
  JOIN exercises e ON e.slug = 'gym-farmer-carry'
ON CONFLICT (exercise_id, level, mode) DO NOTHING;

