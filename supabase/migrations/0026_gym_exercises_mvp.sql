-- НЕ ВЫКАТЫВАТЬ ДО СОГЛАСОВАНИЯ С РЕВМАТОЛОГОМ. Ветка feature/gym-exercises-mvp.
--
-- Девятнадцать упражнений, только общий режим. Режим Бехтерева их не
-- получает ни при каком ответе анкеты: механика запрета уже стоит на
-- снаряде (GIMN-022), и эти упражнения все со снарядом, кроме планки —
-- а планка здесь берётся существующая.
--
-- Планку не заводим: gen-plank уже есть, в том же общем режиме и с тем же
-- движением. Второй строкой она стала бы вторым «правильным» описанием
-- одного упражнения, и рано или поздно правки разошлись бы.
--
-- Уровни расставлены не по учебнику. В Starting Strength новичок начинает
-- сразу со штанги, но там рядом стоит тренер и правит спину руками. Здесь
-- тренера нет, а среди занимающихся есть люди с больной спиной, поэтому
-- новичку достаются кубковый присед, жим гантелей и тренажёры, а штанга
-- открывается со среднего уровня — когда за плечами двадцать тренировок,
-- рост рабочего веса и двенадцать недель без пропусков (блок F).
-- Ревматолог может решить иначе: уровень меняется в одной колонке.
--
-- Картинок нет: image_url остаётся NULL, изображения придут из wger
-- (GIMN-025), когда Роман пришлёт архив.

-- ---------------------------------------------------------------------------
-- 1. Второй снаряд.
--
-- До сих пор упражнению хватало одного: турник, брусья или ничего. В зале
-- так не выходит — жим лёжа требует и штангу, и скамью, присед со штангой
-- ещё и стойку. Записать один снаряд из двух значит показать упражнение
-- тому, у кого второго нет: человек с гантелями, но без скамьи, получил бы
-- жим лёжа и делал бы его на полу, не понимая, что программа ошиблась.
--
-- Основная колонка остаётся основной — на ней индекс и вся прежняя логика,
-- и у 76 старых упражнений список дополнительных пуст, то есть для них не
-- меняется ничего.
-- ---------------------------------------------------------------------------
